// Runs the web build's own generator (from reference/last-sale-source.html) with Node
// and writes golden data for tests/test_generator_golden.gd.
// Usage: node tools/make_generator_golden.js
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'reference/last-sale-source.html'), 'utf8');
const start = html.indexOf('window.PullTabRNG=');
const end = html.indexOf('</script>', start);
const window = {};
new Function('window', html.slice(start, end))(window);
const { FORMS, makeRandom, buildDeal } = window.PullTabRNG;

// Canonical text for one ticket; the GDScript test builds the same string.
const line = t => [t.no, t.tier, t.prize, t.winRow, t.serial,
  t.rows.map(r => r.join('')).join('.'), t.marks.map(m => m.join('')).join('.'), t.verify || ''].join(',');

const seeds = ['G-0001', 'G-0002', 'G-0137', 'seed with spaces', '中文种子'];
const boxes = [];
for (const seed of seeds) for (const form of FORMS) {
  const d = buildDeal(form, seed);
  const lines = d.tickets.map(line);
  boxes.push({
    form: form.id, seed, heat: d.heat, size: d.size,
    counts: d.tiers.map(t => t.count),
    first: lines.slice(0, 5),
    sha256: crypto.createHash('sha256').update(lines.join('\n')).digest('hex'),
  });
}
const r = makeRandom('G-0001|catch');
// Stored as the raw 32-bit integers (r() * 2^32) so no decimal round trip is involved.
const rng = Array.from({ length: 20 }, () => r() * 4294967296);

const out = { note: 'Generated by tools/make_generator_golden.js from reference/last-sale-source.html', rng_seed: 'G-0001|catch', rng, boxes };
fs.writeFileSync(path.join(root, 'tests/fixtures/generator_golden.json'), JSON.stringify(out, null, 1) + '\n');
console.log('wrote', boxes.length, 'boxes');
